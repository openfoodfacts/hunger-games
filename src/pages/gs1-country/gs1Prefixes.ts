export function getGs1CountryByPrefix(prefix: string): Gs1CountryConfig {
  return GS1_COUNTRIES.find((c) => c.prefix === prefix) ?? GS1_COUNTRIES[0];
}

/**
 * Converts a GS1 prefix (e.g. "385" or "76") into a 13-character OFF facet pattern
 * (e.g. "385xxxxxxxxxx" or "76xxxxxxxxxxx").
 */
export function getFacetCodePattern(prefix: string): string {
  return prefix.padEnd(13, "x");
}
